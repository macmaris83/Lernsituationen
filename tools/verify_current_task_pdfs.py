#!/usr/bin/env python3
"""Verify PDFs generated from current task HTML and refresh editable time maps.

The distinctive time colour is a stable locator, not an extra printed marker.
No lesson content or original material PDFs are generated by this helper.
"""
import argparse
import hashlib
import json
import re
import unicodedata
from pathlib import Path

import fitz

TIME_COLOUR = 0x365F7C
TIME_TEXT = re.compile(r"ca\.\s*([0-9]+(?:[.,][0-9]+)?)\s+Minuten")


def compact(text):
    text = unicodedata.normalize("NFKC", text).replace("\u00ad", "")
    return "".join(c.lower() for c in text if c.isalnum())


def read_assignment(file):
    return json.loads(file.read_text().split("=", 1)[1].strip().rstrip(";"))


def inspect(root, entry, output):
    file = root / entry["master"] / entry["file"]
    doc = fitz.open(file)
    if not len(doc):
        raise AssertionError(f"Empty PDF: {file}")
    prefix = re.sub(r"[^a-zA-Z0-9_-]", "_", entry["id"]+"_"+Path(entry["file"]).stem)
    # Save visual evidence before assertions, including for a failed document.
    doc[0].get_pixmap(matrix=fitz.Matrix(1.15, 1.15), alpha=False).save(output / f"{prefix}_p1.png")
    text = "".join(page.get_text(sort=True) for page in doc)
    content = compact(text)
    markers, visible_numbers = [], []
    for page_no, page in enumerate(doc):
        for block in page.get_text("dict")["blocks"]:
            for line in block.get("lines", []):
                if entry["kind"] in ("phase", "workbook"):
                    for span in line["spans"]:
                        heading = re.fullmatch(r"Aufgabe\s+(\d+)", span["text"].strip())
                        if heading and abs(span["size"]-11) < .2 and "bold" in span["font"].lower():
                            visible_numbers.append(int(heading[1]))
                spans = [s for s in line["spans"] if s["color"] == TIME_COLOUR]
                if not spans:
                    continue
                label = "".join(s["text"] for s in spans)
                match = TIME_TEXT.fullmatch(label.strip())
                if not match:
                    continue
                box = fitz.Rect(spans[0]["bbox"])
                for span in spans[1:]:
                    box |= fitz.Rect(span["bbox"])
                if box.x0 < 0 or box.y0 < 0 or box.x1 > page.rect.width + 1 or box.y1 > page.rect.height + 1:
                    raise AssertionError(f"Time label outside page in {file}, page {page_no+1}")
                markers.append({"minutes": float(match[1].replace(",", ".")), "page": page_no,
                                "x": box.x0, "y": box.y0, "width": min(150, page.rect.width-box.x0-14),
                                "height": box.height+1, "fontSize": spans[0]["size"],
                                "baselineFromTop": spans[0]["origin"][1]-box.y0,
                                "color": [0x36/255, 0x5F/255, 0x7C/255], "background": [1, 1, 1]})
    tasks = entry["tasks"]
    if entry["kind"] in ("phase", "workbook") and visible_numbers != [t["number"] for t in tasks]:
        raise AssertionError(f"Visible PDF numbering mismatch: {entry['id']} {entry['file']}: {visible_numbers}")
    if len(markers) != len(tasks):
        raise AssertionError(f"{entry['id']} {entry['file']}: {len(markers)} task time labels, expected {len(tasks)}")
    time_map = []
    for task, marker in zip(tasks, markers):
        if abs(marker.pop("minutes") - task["minutes"]) > .01:
            raise AssertionError(f"Task time/order mismatch: {entry['id']} {task['id']}")
        expected = compact(task["text"])
        # Long paragraphs can be split across pages; check their first and last
        # substantial text fragments without relying on PDF line-break choices.
        for fragment in (expected[:40], expected[-40:]):
            if fragment and fragment not in content:
                raise AssertionError(f"Task text missing in {entry['id']} {entry['file']}: {task['id']} {fragment!r}")
        time_map.append({"taskId": task["id"], "mode": 1, "phase": task["phase"],
                         "originalMinutes": task["minutes"], **marker})
    record = {key: entry[key] for key in ("id", "master", "file", "kind", "inputHash")}
    record.update(pages=len(doc), taskNumbers=[t["number"] for t in tasks],
                  taskIds=[t["id"] for t in tasks], sha256=hashlib.sha256(file.read_bytes()).hexdigest())
    # Representative visual evidence: first and final task pages of each phase,
    # plus first page of the full print. No modification of the source PDFs.
    selected = {0, markers[-1]["page"]} if entry["kind"] == "phase" else {0} if entry["kind"] == "print" else set()
    for page_no in sorted(selected):
        if page_no == 0:
            continue
        doc[page_no].get_pixmap(matrix=fitz.Matrix(1.15, 1.15), alpha=False).save(output / f"{prefix}_p{page_no+1}.png")
    doc.close()
    return record, time_map


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--plan", type=Path, required=True)
    args = parser.parse_args()
    root, output = args.root, args.plan.parent
    plan = json.loads(args.plan.read_text())
    records, maps, errors = [], {}, []
    for entry in plan:
        try:
            record, time_map = inspect(root, entry, output)
        except Exception as error:
            errors.append({"id": entry["id"], "file": entry["file"], "error": str(error)})
            continue
        records.append(record)
        map_file = root / entry["master"] / "assets/pdf-task-times-map.js"
        if map_file.exists():
            if map_file not in maps:
                maps[map_file] = read_assignment(map_file)
            maps[map_file][entry["file"]] = time_map
    (output / "verification-errors.json").write_text(json.dumps(errors, ensure_ascii=False, indent=2)+"\n")
    if errors:
        for error in errors:
            print(f"PDF verification failed: {error['id']} {error['file']}: {error['error']}")
        raise SystemExit(1)
    # Write only after every rendered file passed the content/time checks.
    for file, mapping in maps.items():
        folder = file.parent.parent
        mapping = {key: entries for key, entries in mapping.items() if (folder / key).exists()}
        file.write_text("window.BRC_PDF_TIME_MAP="+json.dumps(mapping, ensure_ascii=False, separators=(",", ":"))+";\n")
    report = root / "tools/fixtures/current-task-pdfs.json"
    old = json.loads(report.read_text()) if report.exists() else []
    changed = {entry["id"] for entry in plan}
    records = [entry for entry in old if entry["id"] not in changed] + records
    records.sort(key=lambda entry: (entry["id"], entry["file"]))
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(json.dumps(records, ensure_ascii=False, indent=2)+"\n")
    print(f"Verified {len(plan)} PDFs; task text, numbering and editable time positions recorded.")


if __name__ == "__main__":
    main()
